-- Planned-schedule history (rolling window, 35 days by default).
-- Written by scripts/gtfs-import.js (nightly) and scripts/gtfs-backfill.js.
-- Unlike gtfs_*, these tables are never dropped. Safe to run repeatedly.
--
-- Storage idea: descriptive rows are content-addressed. content_hash is an md5 of
-- the row's content (as uuid), so an unchanged stop / route / pattern / timing /
-- trip / service group is stored once, however many days use it. A new row
-- appears only when something actually changed. Per day only hist_service_days
-- grows: which service groups ran on that date.
--
-- Rows reference each other by short integer keys (*_key); the 16-byte hash is
-- stored once per row, only for de-duplication.
--
-- Stable identifiers (stop_code, route_short_name, agency, route_desc) are stored
-- alongside the GTFS ids, because GTFS ids can change between feeds.

-- One-time migration: the first version used uuid keys everywhere. Drop it.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema = 'public' AND table_name = 'hist_stops'
               AND column_name = 'stop_key' AND data_type = 'uuid') THEN
    DROP TABLE public.hist_service_days, public.hist_service_trips, public.hist_services,
               public.hist_trips, public.hist_profile_offsets, public.hist_profiles,
               public.hist_pattern_stops, public.hist_patterns, public.hist_routes,
               public.hist_stops, public.hist_days CASCADE;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.hist_stops (
  stop_key        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_hash    uuid    NOT NULL UNIQUE,
  stop_id         integer NOT NULL,
  stop_code       integer,
  stop_name       text    NOT NULL,
  stop_desc       text,
  stop_lat        double precision,
  stop_lon        double precision,
  location_type   smallint,
  parent_station  integer,
  zone_id         text
);
CREATE INDEX IF NOT EXISTS hist_stops_stop_code_idx ON public.hist_stops (stop_code);

CREATE TABLE IF NOT EXISTS public.hist_routes (
  route_key         integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_hash      uuid     NOT NULL UNIQUE,
  route_id          integer  NOT NULL,
  agency_id         integer  NOT NULL,
  agency_name       text,
  route_short_name  text,
  route_long_name   text,
  route_desc        text,
  route_type        smallint
);
CREATE INDEX IF NOT EXISTS hist_routes_short_name_idx ON public.hist_routes (route_short_name);

-- Ordered stop list of a route
CREATE TABLE IF NOT EXISTS public.hist_patterns (
  pattern_key   integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_hash  uuid     NOT NULL UNIQUE,
  route_key     integer  NOT NULL REFERENCES public.hist_routes (route_key),
  num_stops     smallint NOT NULL
);
CREATE INDEX IF NOT EXISTS hist_patterns_route_idx ON public.hist_patterns (route_key);

CREATE TABLE IF NOT EXISTS public.hist_pattern_stops (
  pattern_key    integer  NOT NULL REFERENCES public.hist_patterns (pattern_key) ON DELETE CASCADE,
  stop_sequence  smallint NOT NULL,
  stop_key       integer  NOT NULL REFERENCES public.hist_stops (stop_key),
  pickup_type    smallint,
  drop_off_type  smallint,
  PRIMARY KEY (pattern_key, stop_sequence)
);
CREATE INDEX IF NOT EXISTS hist_pattern_stops_stop_idx ON public.hist_pattern_stops (stop_key);

-- Timing of a pattern: seconds after origin departure at each stop
CREATE TABLE IF NOT EXISTS public.hist_profiles (
  profile_key   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_hash  uuid    NOT NULL UNIQUE,
  pattern_key   integer NOT NULL REFERENCES public.hist_patterns (pattern_key)
);
CREATE INDEX IF NOT EXISTS hist_profiles_pattern_idx ON public.hist_profiles (pattern_key);

CREATE TABLE IF NOT EXISTS public.hist_profile_offsets (
  profile_key    integer  NOT NULL REFERENCES public.hist_profiles (profile_key) ON DELETE CASCADE,
  stop_sequence  smallint NOT NULL,
  offset_sec     integer  NOT NULL,
  PRIMARY KEY (profile_key, stop_sequence)
);

-- A trip without its feed-specific trip_id (which changes daily)
CREATE TABLE IF NOT EXISTS public.hist_trips (
  trip_key               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_hash           uuid    NOT NULL UNIQUE,
  profile_key            integer NOT NULL REFERENCES public.hist_profiles (profile_key),
  origin_departure_sec   integer NOT NULL,
  trip_headsign          text,
  direction_id           smallint,
  wheelchair_accessible  smallint
);
CREATE INDEX IF NOT EXISTS hist_trips_profile_idx ON public.hist_trips (profile_key);

-- A group of trips that run together (content of one GTFS service_id)
CREATE TABLE IF NOT EXISTS public.hist_services (
  service_key   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_hash  uuid    NOT NULL UNIQUE,
  num_trips     integer NOT NULL
);

CREATE TABLE IF NOT EXISTS public.hist_service_trips (
  service_key  integer  NOT NULL REFERENCES public.hist_services (service_key) ON DELETE CASCADE,
  trip_key     integer  NOT NULL REFERENCES public.hist_trips (trip_key),
  trip_count   smallint NOT NULL DEFAULT 1,   -- identical trips in the group
  PRIMARY KEY (service_key, trip_key)
);
CREATE INDEX IF NOT EXISTS hist_service_trips_trip_idx ON public.hist_service_trips (trip_key);

-- The only table that grows every day: which service groups ran on a date
CREATE TABLE IF NOT EXISTS public.hist_service_days (
  service_date   date     NOT NULL,
  service_key    integer  NOT NULL REFERENCES public.hist_services (service_key),
  service_count  smallint NOT NULL DEFAULT 1,
  PRIMARY KEY (service_date, service_key)
);
CREATE INDEX IF NOT EXISTS hist_service_days_service_idx ON public.hist_service_days (service_key);

-- Which dates are covered, and from which file
CREATE TABLE IF NOT EXISTS public.hist_days (
  service_date        date        PRIMARY KEY,
  source              text        NOT NULL CHECK (source IN ('mot', 'archive')),
  source_url          text        NOT NULL,
  feed_last_modified  timestamptz,
  num_services        integer     NOT NULL,
  num_trips           integer     NOT NULL,
  loaded_at           timestamptz NOT NULL DEFAULT now()
);

-- Every planned trip, on every service date it ran, at every stop of its pattern.
-- The one place that joins the hist_* tables; the functions below filter it
-- (Postgres pushes their WHERE conditions down into the joins).
-- Times are seconds after midnight of service_date and may be >= 24:00.
-- trip_key is the stable trip id (GTFS trip_id changes with every feed).
CREATE OR REPLACE VIEW public.hist_stop_trips WITH (security_invoker = true) AS
SELECT sd.service_date,
       tr.trip_key,
       tr.direction_id,
       tr.trip_headsign,
       tr.origin_departure_sec,
       tr.origin_departure_sec + po.offset_sec AS departure_sec,
       r.agency_name,
       r.route_short_name,
       r.route_desc,
       r.route_long_name,
       s.stop_id,
       s.stop_code,
       s.stop_name,
       ps.stop_sequence,
       ps.pickup_type
FROM hist_stops s
JOIN hist_pattern_stops   ps ON ps.stop_key = s.stop_key
JOIN hist_patterns        pa ON pa.pattern_key = ps.pattern_key
JOIN hist_routes          r  ON r.route_key = pa.route_key
JOIN hist_profiles        pf ON pf.pattern_key = pa.pattern_key
JOIN hist_profile_offsets po ON po.profile_key = pf.profile_key AND po.stop_sequence = ps.stop_sequence
JOIN hist_trips           tr ON tr.profile_key = pf.profile_key
JOIN hist_service_trips   st ON st.trip_key = tr.trip_key
JOIN hist_service_days    sd ON sd.service_key = st.service_key;

-- Planned departures of a line (or of all lines when p_line is NULL) from a stop
-- on a calendar date. Covers trips of the previous service day that run after
-- midnight (GTFS times >= 24:00). planned_at is local Israel time.
-- Returns no rows when the date is not in hist_days; check coverage there.
CREATE OR REPLACE FUNCTION public.gtfs_planned_departures(
  p_date      date,
  p_stop_code integer,
  p_line      text DEFAULT NULL
)
RETURNS TABLE (
  planned_at        timestamp,
  service_date      date,
  departure_sec     integer,
  agency_name       text,
  route_short_name  text,
  route_desc        text,
  route_long_name   text,
  trip_headsign     text,
  stop_id           integer,
  stop_name         text,
  stop_sequence     smallint,
  pickup_type       smallint
)
LANGUAGE sql
STABLE
SET search_path = public
AS $$
  -- DISTINCT inside a subquery: when the planner inlines this function into a
  -- caller's query, a top-level DISTINCT + ORDER BY can fail
  SELECT d.* FROM (
  SELECT DISTINCT
         v.service_date + make_interval(secs => v.departure_sec) AS planned_at,
         v.service_date,
         v.departure_sec,
         v.agency_name,
         v.route_short_name,
         v.route_desc,
         v.route_long_name,
         v.trip_headsign,
         v.stop_id,
         v.stop_name,
         v.stop_sequence,
         v.pickup_type
  FROM hist_stop_trips v
  WHERE v.stop_code = p_stop_code
    AND v.service_date IN (p_date - 1, p_date)
    AND (p_line IS NULL OR v.route_short_name = p_line)
    AND (v.service_date + make_interval(secs => v.departure_sec))::date = p_date
  ) d
  ORDER BY d.planned_at, d.route_short_name;
$$;

-- Trips of a line that stop at a stop and leave their FIRST stop (origin) between
-- p_from and p_to (local Israel time, inclusive). Used to check a departure time
-- keyed by a caller. Trips after midnight (origin time >= 24:00) belong to the
-- previous service day, so that day is searched too.
-- Service days come from hist_service_days (calendar already applied per date).
CREATE OR REPLACE FUNCTION public.gtfs_trips_by_origin_departure(
  p_stop_code integer,
  p_line      text,
  p_from      timestamp,
  p_to        timestamp
)
RETURNS TABLE (
  trip_key              integer,
  service_date          date,
  origin_departure_at   timestamp,
  origin_departure_sec  integer,
  direction_id          smallint,
  trip_headsign         text,
  agency_name           text,
  route_desc            text,
  route_long_name       text
)
LANGUAGE sql
STABLE
SET search_path = public
AS $$
  SELECT d.* FROM (
  SELECT DISTINCT
         v.trip_key,
         v.service_date,
         v.service_date + make_interval(secs => v.origin_departure_sec) AS origin_departure_at,
         v.origin_departure_sec,
         v.direction_id,
         v.trip_headsign,
         v.agency_name,
         v.route_desc,
         v.route_long_name
  FROM hist_stop_trips v
  WHERE v.stop_code = p_stop_code
    AND v.route_short_name = p_line
    AND v.service_date BETWEEN p_from::date - 1 AND p_to::date
    AND v.service_date + make_interval(secs => v.origin_departure_sec) BETWEEN p_from AND p_to
  ) d
  ORDER BY d.origin_departure_at, d.trip_key;
$$;

-- Access: RLS on, no policies. Only the server key (service_role) may read / execute.
DO $$
DECLARE
  t text;
  tables text[] := ARRAY['hist_stops', 'hist_routes', 'hist_patterns', 'hist_pattern_stops', 'hist_profiles',
                         'hist_profile_offsets', 'hist_trips', 'hist_services', 'hist_service_trips',
                         'hist_service_days', 'hist_days'];
BEGIN
  FOREACH t IN ARRAY tables LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', t);
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
      EXECUTE format('REVOKE ALL ON public.%I FROM service_role', t);
      EXECUTE format('GRANT SELECT ON public.%I TO service_role', t);
    END IF;
  END LOOP;

  -- The view runs as the caller (security_invoker), so RLS on the tables still applies
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON public.hist_stop_trips FROM anon, authenticated;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    REVOKE ALL ON public.hist_stop_trips FROM service_role;
    GRANT SELECT ON public.hist_stop_trips TO service_role;
  END IF;

  FOREACH t IN ARRAY ARRAY['public.gtfs_planned_departures(date, integer, text)',
                           'public.gtfs_trips_by_origin_departure(integer, text, timestamp, timestamp)'] LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON FUNCTION %s FROM anon, authenticated', t);
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
      EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role', t);
    END IF;
  END LOOP;
END $$;
